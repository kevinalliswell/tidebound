const { chromium } = require('C:/Users/Kevin-pc/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');
(async () => {
  fs.mkdirSync('test-results', { recursive: true });
  const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', args: ['--enable-webgl', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', m => { if (m.type() === 'error' && !m.text().includes('favicon')) errors.push(m.text()); });
  await page.goto('http://127.0.0.1:5175/', { waitUntil: 'networkidle' });
  await page.waitForSelector('#loading.hidden', { timeout: 60000 });
  await page.waitForTimeout(1500);
  await page.screenshot({ path: 'test-results/harbor.png' });
  assert.ok(await page.locator('#scene canvas').count());
  assert.equal(await page.title(), '潮生 TIDEBOUND · 风栖港');
  assert.equal((await page.evaluate(() => window.tidebound.snapshot())).money, 36);
  console.log('Loaded 3D harbor', await page.evaluate(() => window.tidebound.status()));
  await page.locator('[data-action="fish"]').first().click();
  await page.waitForFunction(() => window.tidebound.status().fishing === 'bite', null, { timeout: 60000 });
  await page.locator('[data-action="hook"]').click();
  for (let i = 0; i < 18; i++) {
    const stage = await page.evaluate(() => window.tidebound.status().fishing);
    if (stage !== 'fight') break;
    await page.locator('[data-action="reel"]').dispatchEvent('pointerdown');
    await page.waitForTimeout(850);
    await page.mouse.up();
    if (await page.locator('[data-action="skill"]').count()) await page.locator('[data-action="skill"]').click();
    await page.waitForTimeout(550);
  }
  const caught = await page.evaluate(() => window.tidebound.snapshot().totalCaught);
  assert.ok(caught > 0, 'catch a fish through actual UI');
  console.log('Caught fish through hook / reel / tension UI');
  await page.locator('[data-nav="warehouse"]').click();
  await page.waitForSelector('#panel-title:text("渔获与仓库")', { timeout: 60000 });
  await page.locator('[data-action="sell"][data-source="bag"]').click();
  assert.ok((await page.evaluate(() => window.tidebound.snapshot())).totalEarned > 0);
  console.log('Walked to warehouse and sold catch');
  await page.locator('[data-action="close"]').click();
  await page.locator('[data-action="partners"]').first().click();
  await page.locator('[data-action="feed-parrot"][data-id="parrot-leaf"]').click();
  assert.equal((await page.evaluate(() => window.tidebound.snapshot())).parrots[1].trust, 20);
  await page.locator('[data-action="close"]').click();
  await page.locator('[data-action="boat"]').first().click();
  await page.locator('[data-action="dive"]').click();
  await page.waitForTimeout(2000);
  const dive = await page.evaluate(() => ({ status: window.tidebound.status(), state: window.tidebound.snapshot() }));
  assert.equal(dive.status.diving, true); assert.ok(dive.state.oxygen < 100);
  await page.screenshot({ path: 'test-results/underwater.png' });
  console.log('Diving consumes oxygen, underwater scene rendered');
  await page.keyboard.press('Escape');
  const before = await page.evaluate(() => window.tidebound.snapshot().oxygen);
  await page.waitForTimeout(1500);
  assert.equal(await page.evaluate(() => window.tidebound.snapshot().oxygen), before);
  await page.locator('[data-action="resume"]').click();
  await page.locator('[data-action="rise"]').click();
  await page.waitForTimeout(1500);
  await page.locator('#context [data-action="boat"]').click();
  assert.equal((await page.evaluate(() => window.tidebound.status())).diving, false);
  assert.equal((await page.evaluate(() => window.tidebound.snapshot())).oxygen, 100);
  console.log('Pause freezes oxygen; surface and board refills oxygen');
  await page.reload({ waitUntil: 'networkidle' });
  assert.ok((await page.evaluate(() => window.tidebound.snapshot())).totalCaught > 0);
  console.log('Progress persists after reload');
  await page.setViewportSize({ width: 900, height: 650 });
  await page.waitForTimeout(500); await page.screenshot({ path: 'test-results/compact.png' });
  await browser.close();
  assert.deepEqual(errors, []);
  console.log('Browser smoke checks passed with no JavaScript errors');
})().catch(error => { console.error(error); process.exit(1); });
